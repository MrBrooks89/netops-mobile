/**
 * Curated port reference dataset.
 *
 * Inclusion policy: IANA well-known assignments plus widely-used application
 * defaults that network engineers actually look up (databases, containers,
 * monitoring, VPNs, dev servers). Where a popular default differs from the
 * IANA service name, the entry uses the practical name and the description
 * says what it is.
 *
 * This is deliberately a curated list, not the full IANA registry (~14k
 * entries). M2 swaps it for a seeded SQLite `ports` table with the same shape.
 *
 * Every (port, proto) pair is unique — enforced by tests.
 *
 * Pure TS — no React Native imports.
 */

export type PortProto = 'tcp' | 'udp' | 'sctp';

export interface PortEntry {
  readonly port: number;
  readonly proto: PortProto;
  readonly service: string;
  readonly description: string;
}

const T = (port: number, service: string, description: string): PortEntry => ({
  port,
  proto: 'tcp',
  service,
  description,
});

const U = (port: number, service: string, description: string): PortEntry => ({
  port,
  proto: 'udp',
  service,
  description,
});

/** Registered on both TCP and UDP with the same service name. */
const TU = (port: number, service: string, description: string): PortEntry[] => [
  T(port, service, description),
  U(port, service, description),
];

